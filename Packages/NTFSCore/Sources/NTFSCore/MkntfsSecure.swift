    /// Build the full `$SDS` data stream sized to `allocBytes` (cluster-rounded
    /// $SDS allocation). Two descriptor entries at offsets 0 and 128, mirrored
    /// as a block at 0x40000.
    static func makeSecureSDSStream(allocBytes: Int) -> Data {
        var d = Data(count: allocBytes)
        func writeEntry(at off: Int, hash: UInt32, id: UInt32, sd: [UInt8]) {
            MFTRecord.writeU32LE(into: &d, at: off + 0,  value: hash)
            MFTRecord.writeU32LE(into: &d, at: off + 4,  value: id)
            MFTRecord.writeU64LE(into: &d, at: off + 8,  value: UInt64(off))     // self offset within block
            MFTRecord.writeU32LE(into: &d, at: off + 16, value: UInt32(sdsEntryHeaderLen + sd.count))  // 124
            for (i, b) in sd.enumerated() { d[d.startIndex + off + 20 + i] = b }
        }
        writeEntry(at: 0,   hash: sd256Hash, id: 256, sd: sd256)
        writeEntry(at: 128, hash: sd257Hash, id: 257, sd: sd257)
        // Mirror the 252-byte descriptor block at 0x40000.
        for i in 0..<252 { d[d.startIndex + sdsMirrorOffset + i] = d[d.startIndex + i] }
        return d
    }
}
