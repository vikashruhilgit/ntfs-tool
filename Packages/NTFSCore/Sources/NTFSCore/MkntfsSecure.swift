import Foundation

// Builds a spec-valid `$Secure` metafile (MFT record 9) for the formatter.
//
// Real NTFS (mkntfs/Windows) `$Secure` is a VIEW_INDEX file made of:
//   • `$DATA:$SDS`  — the Security Descriptor Stream: a list of SDS_ENTRY
//     records (20-byte header + a self-relative security descriptor), with the
//     WHOLE block mirrored at offset 0x40000 (NTFS redundancy convention).
//   • `$INDEX_ROOT:$SDH` — index of descriptors keyed by (hash, security_id),
//     collation NTOFS_SECURITY_HASH (0x12).
//   • `$INDEX_ROOT:$SII` — index of descriptors keyed by security_id,
//     collation NTOFS_ULONG (0x10).
//
// ntfs-3g (and Windows) HARD-REQUIRE these at mount: opening `$Secure` and
// reading `$SDH`/`$SII` is part of mounting a v3.x volume. An empty/stub
// `$Secure` makes ntfs-3g fail with "Failed to open $Secure".
//
// The default descriptor set below (two descriptors, security_id 256 and 257)
// and the matching `$SDH`/`$SII` index bodies are CONSTANT on-disk format data,
// captured from a real `mkntfs` volume (clean-room: reproducing the documented
// on-disk layout, not copying mkntfs source). Security ids 256/257 are the
// canonical mkntfs defaults; 257 (a slightly broader DACL) is what new files
// inherit, and is stamped into every record's $STANDARD_INFORMATION.security_id.
extension Mkntfs {

